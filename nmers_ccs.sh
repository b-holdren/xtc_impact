#!/bin/bash
#SBATCH --job-name=xtc_chunk
#SBATCH --partition=batch
#SBATCH --nodes=1
#SBATCH --ntasks=1
#SBATCH --cpus-per-task=1
#SBATCH --mem=8G
#SBATCH --time=24:00:00                
#SBATCH --array=0-199                   
#SBATCH --output=logs/%x_%A_%a.out
#SBATCH --error=logs/%x_%A_%a.err
#SBATCH --mail-user=bradyholdren@ucsb.edu
#SBATCH --mail-type=all

#==================================================
# GLOBAL CONFIG
#==================================================
CONDA_ENV="MDanalysis"
source config.sh

#==================================================
# 1. ENVIRONMENT SETUP
#==================================================
module load miniconda/3.13
module load gromacs/2025.1

eval "$(conda shell.bash hook)"
conda activate "$CONDA_ENV"
export OMP_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1 MKL_NUM_THREADS=1 \
       NUMEXPR_NUM_THREADS=1 BLIS_NUM_THREADS=1

#==================================================
# 2. ARRAY INDEX MAPPING
#==================================================
IDX=${SLURM_ARRAY_TASK_ID}

# Map IDX to N-mer size and Chunk index
N=${N_MIN}
CHUNK=${IDX}
if (( N_CHUNKS > 1 )); then
  N=$(( N_MIN + IDX / N_CHUNKS ))
  CHUNK=$(( IDX % N_CHUNKS ))
fi

# Calculate Frame bounds for the Python script
START_FRAME=$(( CHUNK * FRAME_CHUNK_SIZE ))
STOP_FRAME=$(( START_FRAME + FRAME_CHUNK_SIZE ))

#==================================================
# 3. SYSTEM ITERATION & PIPELINE EXECUTION
#==================================================
# Read valid system directories from config.sh
RUN_FOLDER=("${MOLS[@]}")

for CURRENT_RUN in "${RUN_FOLDER[@]}"; do
    echo "========================================================="
    echo "Processing System: $CURRENT_RUN | Array Job: $IDX | Chunk: $CHUNK"
    
    # Define absolute paths for the current system
    XTC_FILE="${CURRENT_RUN}/${XTC_NAME}"
    TPR_FILE="${CURRENT_RUN}/${TPR_NAME}"
    OUT_DIR_SCRATCH="${CURRENT_RUN}/scratch"
    DATA_OUT="${OUT_DIR_SCRATCH}/n${N}_chunk${CHUNK}_data.tmp"
    
    # Validate input files exist before proceeding
    if [ ! -f "$XTC_FILE" ] || [ ! -f "$TPR_FILE" ]; then
        echo "WARNING: Missing .xtc or .tpr in $CURRENT_RUN. Skipping system."
        continue
    fi

    # Initialize scratch directory and clear previous run data
    mkdir -p "$OUT_DIR_SCRATCH"
    rm -f "$DATA_OUT"

    # -----------------------------------------------------------
    # PROCESS A: Complex Isolation & PDB Generation
    # -----------------------------------------------------------
    echo "-> Isolating target complex and generating PDBs via Python..."
    
    python "$PYTHON_SCRIPT" \
      --topol "$TPR_FILE" \
      --traj "$XTC_FILE" \
      --target "$N" \
      --start "$START_FRAME" \
      --stop "$STOP_FRAME" \
      --out "$OUT_DIR_SCRATCH/chunk${CHUNK}"

    # -----------------------------------------------------------
    # PROCESS B: CCS Calculation via IMPACT
    # -----------------------------------------------------------
    echo "-> Calculating CCS on isolated complexes..."
    
    # Process all PDBs generated by the Python script for this chunk
    for f in "$OUT_DIR_SCRATCH"/n${N}/chunk${CHUNK}_n${N}_frame*.pdb; do
        # Guard clause in case the Python script yielded no frames
        [ -e "$f" ] || { echo "No PDB frames found for chunk $CHUNK in $CURRENT_RUN."; continue; }
        
        # Attempt to extract trajectory time from the PDB REMARK/TITLE header
        TIME_PS=$(grep -m 1 "t=" "$f" | awk -F "t=" '{print $2}' | awk '{print $1}' || true)
        
        # Fallback: Extract frame index and instance from filename
        if [ -z "$TIME_PS" ]; then
            RAW_SUFFIX=$(basename "$f" .pdb | awk -F '_frame' '{print $2}')
            # RAW_SUFFIX will be like "001127_i0"
            TIME_PS=$(echo "$RAW_SUFFIX" | awk -F '_i' '{print $1}')
            INSTANCE_ID=$(echo "$RAW_SUFFIX" | awk -F '_i' '{print $2}')
        else
            INSTANCE_ID="0" # Default if header had time but no instance
        fi
        
        # Execute IMPACT and parse the CCS value
        CCS=$("$IMPACT_PATH" "$f" | grep "CCS 1" | awk '{print $(NF-1)}' || true)
        
        # Calculate Beta Strand Percentage via DSSP
        SS_XVG="${f%.pdb}_ss.xvg"
        gmx dssp -s "$f" -f "$f" -num "$SS_XVG" > /dev/null 2>&1
        BETA_PCT=$(grep -v '^[#@]' "$SS_XVG" | awk '{tot=0; for(i=2;i<=11;i++) tot+=$i; if(tot>0) printf "%.3f", $9/tot*100; else print "0.000"}' || true)
        rm -f "$SS_XVG"
        
        # Write valid outputs to the temporary data file (Frame/Time, Instance, CCS, BetaPct)
        if [ -n "$CCS" ] && [ -n "$BETA_PCT" ]; then
            echo -e "${TIME_PS}\t${INSTANCE_ID}\t${CCS}\t${BETA_PCT}" >> "$DATA_OUT"
        fi
        
        # Remove the PDB file to minimize inode usage and storage footprint
        rm -f "$f"
    done
done
1
echo "Array Job $IDX successfully completed all processes!"
